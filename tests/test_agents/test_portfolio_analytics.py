"""方案权重回放与用户净值重建的确定性计算。

金样本的期望值全部由人工按定义算出，不由实现推导——否则测试与实现永远一致，
改公式时静默跟随，失去回归意义（与 ``test_product_scoring.py`` 同一约定）。

═══════════════════════════════════════════════════════════════════════════
接缝 3 derivation —— 2 只标的 × 6 个交易日，初始资金 100.00，目标权重 A 60% / B 40%
═══════════════════════════════════════════════════════════════════════════
费率：买入 0.5%、卖出 0.5%（测试里显式传小费率便于手算）。

T0 建仓（用全部投入资金 100.00 按目标权重买入，买入费用由现金支付）
    买入 A = 60.00 → 费 60.00 × 0.005 = 0.30
    买入 B = 40.00 → 费 40.00 × 0.005 = 0.20
    总费用 = 0.50
    T0 持仓市值 = 60.00 + 40.00 = 100.00（费用是现金支出，不减少持仓市值）
    份额（买入价 = T0 净值）：A = 60.00 / 1.000 = 60.000000
                              B = 40.00 / 2.000 = 20.000000

持有期（权重随价格漂移，不再交易，因此无后续费用）
    T1  A = 60 × 1.020 = 61.200   B = 20 × 2.040 = 40.800   合计 102.000
    T2  A = 60 × 1.010 = 60.600   B = 20 × 2.100 = 42.000   合计 102.600
    T3  A = 60 × 0.980 = 58.800   B = 20 × 1.950 = 39.000   合计  97.800
    T4  A = 60 × 1.050 = 63.000   B = 20 × 2.020 = 40.400   合计 103.400
    T5  A = 60 × 1.030 = 61.800   B = 20 × 2.080 = 41.600   合计 103.400

归一净值曲线（以 T0 持仓市值为基数 100.00）
    T0 100.00/100.00 = 1.000000
    T1 102.00/100.00 = 1.020000
    T2 102.60/100.00 = 1.026000
    T3  97.80/100.00 = 0.978000
    T4 103.40/100.00 = 1.034000
    T5 103.40/100.00 = 1.034000

    约定：费用不进入归一曲线，而是单独作为成本体现。这样无费用的回放 T0 同样是
    1.0，计费与不计费两条曲线可以直接叠在同一张图上比较。

累计收益率（相对**投入资金** 100.00，并扣除已付出的 0.50 费用）
    = (103.40 - 0.50) / 100.00 - 1 = 102.90/100.00 - 1 = 0.029000

最大回撤（以归一净值为路径）
    峰值序列：1.000000, 1.020000, 1.026000, 1.026000, 1.034000, 1.034000
    T3 回撤 = (1.026000 - 0.978000) / 1.026000 = 0.0467836…
    无更深回撤 → 最大回撤 ≈ 0.0467836

日收益率（相邻归一净值之比）
    T1 1.020000/1.000000 - 1 =  0.0200000
    T2 1.026000/1.020000 - 1 =  0.0058824
    T3 0.978000/1.026000 - 1 = -0.0467836
    T4 1.034000/0.978000 - 1 =  0.0572597
    T5 1.034000/1.034000 - 1 =  0.0000000
    均值 = (0.0200000 + 0.0058824 - 0.0467836 + 0.0572597 + 0.0) / 5
         = 0.0363585/5 = 0.00727170
    离差平方和 = (0.01272830)² + (-0.00138930)² + (-0.05405530)² + (0.04998800)² + (-0.00727170)²
               = 0.16200962e-3 + 0.00193016e-3 + 2.92197548e-3 + 2.49880014e-3 + 0.05287762e-3
               = 5.63759302e-3
    总体标准差（除以 n = 5）= sqrt(5.63759302e-3 / 5) = sqrt(1.12751860e-3) = 0.03357854
    年化波动 = 0.03357854 × sqrt(252) = 0.53304…

═══════════════════════════════════════════════════════════════════════════
接缝 4 derivation —— 1 只标的，区间 2026-01-05 ~ 2026-01-08，期间有入金
═══════════════════════════════════════════════════════════════════════════
现金流约定：daily_return[t] = (总资产[t] - 当日现金流[t]) / 总资产[t-1] - 1
    即当日入金/出金算作**日终**流入，不参与当日收益。若让入金参与当日收益，
    用户在高点前入金就会凭空"赚"一笔，TWR 失真。

    日期         净值   份额    市值        当日现金流    现金
    2026-01-05   1.00   0       0.00       +1000 入金    1000
    2026-01-06   0.90   800     720.00     0             200
    2026-01-07   1.10   800     880.00     +500 入金     700
    2026-01-08   1.10   800     880.00     0             700

    份额 800 = 800.00 元 / 1.00 于 01-05 买入（成交价 1.00）。
    总资产 = 市值 + 现金：
      T1 1000.00   T2 920.00   T3 1580.00   T4 1580.00

日收益率
    01-06  (920.00  -   0.00) / 1000.00 - 1 = -0.080000
    01-07  (1580.00 - 500.00) /  920.00 - 1 = 1080/920 - 1 = +0.1739130…
    01-08  (1580.00 -   0.00) / 1580.00 - 1 = 0.000000

TWR
    (1 - 0.08) × (1 + 0.1739130) × (1 + 0) - 1
    = 0.92 × 1.17391304 - 1 = 1.08 - 1 = +0.0800000

    对照：若直接看总资产 1580/1000 - 1 = +0.58，那是**含入金**的错觉。
    剔除 500 入金后真实收益是 +8%。

═══════════════════════════════════════════════════════════════════════════
"""

from __future__ import annotations

from datetime import date

import pytest

from app.agents.portfolio.backtest import replay_weights
from app.agents.portfolio.curve import rebuild_user_curve

A = "110011"
B = "510300"

NAV_SERIES = {
    A: [
        (date(2026, 1, 5), 1.000),
        (date(2026, 1, 6), 1.020),
        (date(2026, 1, 7), 1.010),
        (date(2026, 1, 8), 0.980),
        (date(2026, 1, 9), 1.050),
        (date(2026, 1, 12), 1.030),
    ],
    B: [
        (date(2026, 1, 5), 2.000),
        (date(2026, 1, 6), 2.040),
        (date(2026, 1, 7), 2.100),
        (date(2026, 1, 8), 1.950),
        (date(2026, 1, 9), 2.020),
        (date(2026, 1, 12), 2.080),
    ],
}

WEIGHTS = {A: 0.60, B: 0.40}


def _replay(**overrides):
    kwargs = {
        "nav_series": NAV_SERIES,
        "start": date(2026, 1, 5),
        "end": date(2026, 1, 12),
        "initial_capital": 100.0,
        "fee_buy": 0.005,
        "fee_sell": 0.005,
    }
    kwargs.update(overrides)
    return replay_weights(WEIGHTS, **kwargs)


def test_replay_reproduces_the_hand_derived_curve_and_metrics():
    result = _replay()

    assert result.dates == [
        date(2026, 1, 5),
        date(2026, 1, 6),
        date(2026, 1, 7),
        date(2026, 1, 8),
        date(2026, 1, 9),
        date(2026, 1, 12),
    ]
    assert result.equity_curve == pytest.approx(
        [1.000000, 1.020000, 1.026000, 0.978000, 1.034000, 1.034000], abs=1e-9
    )
    assert result.total_fee == pytest.approx(0.50, abs=1e-9)
    assert result.cumulative_return == pytest.approx(0.029000, abs=1e-9)
    assert result.max_drawdown == pytest.approx(0.0467836, abs=1e-6)
    assert result.annualized_volatility == pytest.approx(0.53304, abs=1e-4)


VIEW_CURVE_ORDERS = [
    {
        "product_code": "510300",
        "side": "buy",
        "shares": 800.0,
        "price": 1.00,
        "trade_date": date(2026, 1, 5),
    },
]

VIEW_CURVE_FLOWS = [
    {"kind": "deposit", "amount": 1000.0, "flow_date": date(2026, 1, 5)},
    {"kind": "deposit", "amount": 500.0, "flow_date": date(2026, 1, 7)},
]

VIEW_CURVE_NAV = {
    "510300": [
        (date(2026, 1, 5), 1.00),
        (date(2026, 1, 6), 0.90),
        (date(2026, 1, 7), 1.10),
        (date(2026, 1, 8), 1.10),
    ],
}


def test_user_curve_excludes_cash_flows_from_the_time_weighted_return():
    curve = rebuild_user_curve(
        orders=VIEW_CURVE_ORDERS,
        flows=VIEW_CURVE_FLOWS,
        nav_series=VIEW_CURVE_NAV,
        start=date(2026, 1, 5),
        end=date(2026, 1, 8),
    )

    assert curve.dates == [
        date(2026, 1, 5),
        date(2026, 1, 6),
        date(2026, 1, 7),
        date(2026, 1, 8),
    ]
    assert curve.total_assets == pytest.approx([1000.0, 920.0, 1580.0, 1580.0])
    assert curve.daily_returns == pytest.approx([-0.080000, 0.1739130, 0.000000], abs=1e-6)
    assert curve.time_weighted_return == pytest.approx(0.08, abs=1e-9)

    # 总资产的涨幅含入金，必须与 TWR 明显不同，否则这个方法就白做了。
    naive = curve.total_assets[-1] / curve.total_assets[0] - 1
    assert naive == pytest.approx(0.58, abs=1e-9)
    assert curve.time_weighted_return != pytest.approx(naive)
